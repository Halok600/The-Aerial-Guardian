#!/usr/bin/env python3
"""
scripts/01_build_dataset.py — VisDrone DET + MOT -> 10-class YOLO dataset.

Training data = VisDrone2019-DET-train (6,471 diverse images) + every Nth
frame of VisDrone2019-MOT-train (56 sequences). Consecutive video frames are
near-duplicates, so subsampling keeps diversity without bloating epochs.
Ignored regions are greyed out in TRAIN images only; val stays untouched so
mAP is comparable with published VisDrone numbers.

Usage
-----
  python scripts/01_build_dataset.py --split train --out datasets/visdrone10 \\
      --det data/visdrone/VisDrone2019-DET-train --mot data/visdrone/VisDrone2019-MOT-train
  python scripts/01_build_dataset.py --split val --out datasets/visdrone10 \\
      --det data/visdrone/VisDrone2019-DET-val --yaml configs/data/visdrone10.yaml
"""
from __future__ import annotations

import argparse
import os
import shutil
import sys
from pathlib import Path

import cv2
from PIL import Image
from tqdm import tqdm

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from src.data.visdrone import (  # noqa: E402
    DEFAULT_CLASS_MAP, PERSON_ONLY_CLASS_MAP, Box, mask_ignored,
    parse_det_file, parse_mot_file, to_yolo_line,
)
from src.utils.classes import VISDRONE_NAMES  # noqa: E402


def _link_or_copy(src: Path, dst: Path) -> None:
    if dst.exists():
        dst.unlink()
    try:
        os.link(src, dst)          # hardlink: instant, no extra disk
    except OSError:
        shutil.copy2(src, dst)


def _write_sample(src_img: Path, dst_img: Path, dst_lbl: Path, boxes: list[Box],
                  img_w: int, img_h: int, class_map: dict[int, int], mask: bool) -> int:
    lines = [line for b in boxes if (line := to_yolo_line(b, img_w, img_h, class_map)) is not None]
    dst_img.parent.mkdir(parents=True, exist_ok=True)
    dst_lbl.parent.mkdir(parents=True, exist_ok=True)
    if mask and any(b.is_ignore for b in boxes):
        image = cv2.imread(str(src_img))
        cv2.imwrite(str(dst_img), mask_ignored(image, boxes), [cv2.IMWRITE_JPEG_QUALITY, 95])
    else:
        _link_or_copy(src_img, dst_img)
    dst_lbl.write_text("".join(f"{line}\n" for line in lines), encoding="utf-8")
    return len(lines)


def build_det_split(det_dir: Path, out_dir: Path, split: str,
                    class_map: dict[int, int], mask: bool) -> dict[str, int]:
    stats = {"images": 0, "boxes": 0}
    for ann in tqdm(sorted((det_dir / "annotations").glob("*.txt")), desc=f"DET {det_dir.name}"):
        src = det_dir / "images" / f"{ann.stem}.jpg"
        if not src.exists():
            continue
        with Image.open(src) as im:
            img_w, img_h = im.size
        stats["boxes"] += _write_sample(
            src, out_dir / "images" / split / src.name, out_dir / "labels" / split / f"{ann.stem}.txt",
            parse_det_file(ann), img_w, img_h, class_map, mask)
        stats["images"] += 1
    return stats


def build_mot_split(mot_dir: Path, out_dir: Path, split: str, stride: int,
                    class_map: dict[int, int], mask: bool) -> dict[str, int]:
    stats = {"images": 0, "boxes": 0}
    for ann in tqdm(sorted((mot_dir / "annotations").glob("*.txt")), desc=f"MOT {mot_dir.name}"):
        seq_dir = mot_dir / "sequences" / ann.stem
        first = next(iter(sorted(seq_dir.glob("*.jpg"))), None)
        if first is None:
            continue
        with Image.open(first) as im:
            img_w, img_h = im.size          # all frames of a sequence share one size
        for frame_id, boxes in sorted(parse_mot_file(ann).items()):
            if (frame_id - 1) % stride:
                continue
            src = seq_dir / f"{frame_id:07d}.jpg"
            if not src.exists():
                continue
            name = f"{ann.stem}_{frame_id:07d}"
            stats["boxes"] += _write_sample(
                src, out_dir / "images" / split / f"{name}.jpg", out_dir / "labels" / split / f"{name}.txt",
                boxes, img_w, img_h, class_map, mask)
            stats["images"] += 1
    return stats


def write_dataset_yaml(out_dir: Path, yaml_path: Path, names: list[str]) -> None:
    yaml_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by scripts/01_build_dataset.py",
        f"path: {Path(out_dir).resolve().as_posix()}",
        "train: images/train",
        "val: images/val",
        f"nc: {len(names)}",
        "names:",
        *[f"  {i}: {n}" for i, n in enumerate(names)],
    ]
    yaml_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[1],
                                formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    p.add_argument("--det", type=Path, nargs="*", default=[], help="VisDrone2019-DET-* split dirs")
    p.add_argument("--mot", type=Path, nargs="*", default=[], help="VisDrone2019-MOT-* split dirs")
    p.add_argument("--split", choices=["train", "val"], required=True)
    p.add_argument("--out", type=Path, default=Path("datasets/visdrone10"))
    p.add_argument("--mot-stride", type=int, default=5)
    p.add_argument("--mask", dest="mask", action="store_true", default=None)
    p.add_argument("--no-mask", dest="mask", action="store_false")
    p.add_argument("--person-only", action="store_true",
                   help="Single 'person' class (pedestrian+people); used to score the old model.")
    p.add_argument("--yaml", type=Path, default=None, help="Write an Ultralytics dataset yaml here.")
    args = p.parse_args()

    mask = (args.split == "train") if args.mask is None else args.mask
    class_map = PERSON_ONLY_CLASS_MAP if args.person_only else DEFAULT_CLASS_MAP
    names = ["person"] if args.person_only else list(VISDRONE_NAMES)

    total = {"images": 0, "boxes": 0}
    for d in args.det:
        for k, v in build_det_split(d, args.out, args.split, class_map, mask).items():
            total[k] += v
    for d in args.mot:
        for k, v in build_mot_split(d, args.out, args.split, args.mot_stride, class_map, mask).items():
            total[k] += v
    print(f"[{args.split}] images={total['images']:,} boxes={total['boxes']:,} mask={mask} -> {args.out}")
    if args.yaml:
        write_dataset_yaml(args.out, args.yaml, names)
        print(f"dataset yaml -> {args.yaml}")


if __name__ == "__main__":
    main()
